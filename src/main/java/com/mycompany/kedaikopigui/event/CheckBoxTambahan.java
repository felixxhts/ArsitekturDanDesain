    private String formatRupiah(int harga){
        return "Rp. " + String.format(java.util.Locale.US, "%,d", harga).replace(",", ".");
    }
    private int hargaLatte = 25000;
    private int gula = 3000;
    private int susu = 5000;
    private int shot = 4000;
    private int es = 1000;
    
    private void updateHarga(){
        int total = hargaLatte;
        if(cbGula.isSelected()){
            total += gula; 
        }
        
        if(cbSusu.isSelected()){
            total += susu;
        }
        
        if(cbShot.isSelected()){
            total += shot;
        }
        
        if(cbEs.isSelected()){
            total += es;
        }
        
        txtTotal.setText(formatRupiah(total));
    }
    

